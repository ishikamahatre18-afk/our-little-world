/** A stride that is co-prime with the bank size spreads the moods out instead of grouping them. */
const STRIDE = 37;

export function questionForDay(dayNo: number): DailyQuestion {
  const length = QUESTIONS.length;
  const index = (((dayNo * STRIDE) % length) + length) % length;
  return QUESTIONS[index] as DailyQuestion;
}
